def validate_letterhead(raw):
    if len(raw) > 10_000_000:
        raise BusinessError("Бланк слишком большой.")
    try:
        with zipfile.ZipFile(io.BytesIO(raw)) as z:
            if sum(i.file_size for i in z.infolist()) > 40_000_000:
                raise BusinessError("Бланк слишком большой после распаковки.")
            if "word/document.xml" not in z.namelist():
                raise BusinessError("Нужен файл DOCX.")
            for name in z.namelist():
                if "vbaProject" in name or "embeddings/" in name:
                    raise BusinessError("Макросы и вложенные объекты в бланке запрещены.")
                if name.endswith(".rels") and b'TargetMode="External"' in z.read(name):
                    raise BusinessError("Удалите внешние ссылки из бланка.")
                if name.endswith(".xml") and any(x in z.read(name) for x in (b"{{", b"{%", b"<!DOCTYPE")):
                    raise BusinessError("Загрузите чистый бланк без шаблонных команд.")
        Document(io.BytesIO(raw))
    except (zipfile.BadZipFile, KeyError, ValueError):
        raise BusinessError("Не удалось прочитать DOCX.") from None


def rub(value):
    return f"{Decimal(str(value)):,.2f}".replace(",", " ").replace(".", ",")


def build_template(letterhead, target):
    """Preserve original headers/footers. All template tags are generated by trusted code."""
    d = Document(io.BytesIO(letterhead))
    body = d._element.body
    for child in list(body):
        if child.tag != qn("w:sectPr"):
            body.remove(child)
    for section in d.sections:
        section.top_margin, section.bottom_margin = Cm(4.1), Cm(2.2)
        section.left_margin, section.right_margin = Cm(2), Cm(2)
    for name, size in [("Normal", 10), ("Title", 19), ("Heading 1", 11)]:
        if name not in d.styles:
            d.styles.add_style(name, 1)
        st = d.styles[name]
        st.font.name, st.font.size, st.font.color.rgb = "Arial", Pt(size), RGBColor(0, 0, 0)
        st.paragraph_format.space_after = Pt(6)
        st.paragraph_format.line_spacing = 1.05
        if name in {"Title", "Heading 1"}:
            st.paragraph_format.keep_with_next = True
        if name == "Heading 1":
            st.font.bold = True
            st.paragraph_format.space_before = Pt(8)
    d.add_paragraph("Коммерческое предложение", "Title")
    d.add_paragraph("№ {{ number }} • {{ issued }} • Версия {{ version }}")
    d.add_paragraph("Кому: {{ client }}\nМенеджер: {{ manager }}")
    d.add_paragraph("Предлагаем к поставке технику в указанной ниже комплектации. Стоимость включает НДС.")
    t = d.add_table(rows=1, cols=4)
    t.autofit = False
    widths = [7.6, 1.5, 3.9, 3.9]
    for c, w in zip(t.columns, widths):
        c.width = Cm(w)
    for cell, text in zip(
        t.rows[0].cells, ["Техника и комплектация", "Кол-во", "Цена, ₽\nс НДС", "Сумма, ₽\nс НДС"]
    ):
        cell.text = text
    t.add_row().cells[0].text = "{%tr for item in items %}"
    r = t.add_row()
    for cell, text in zip(
        r.cells,
        [
            "{{ item.name }}\n{{ item.configuration }}\nНДС {{ item.vat_rate }}%",
            "{{ item.quantity }}",
            "{{ item.unit_display }}",
            "{{ item.total_display }}",
        ],
    ):
        cell.text = text
    t.add_row().cells[0].text = "{%tr endfor %}"
    for index, row in enumerate(t.rows):
        pr = row._tr.get_or_add_trPr()
        pr.append(OxmlElement("w:cantSplit"))
        if index == 0:
            pr.append(OxmlElement("w:tblHeader"))
        for j, cell in enumerate(row.cells):
            cell.width = Cm(widths[j])
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr = cell._tc.get_or_add_tcPr()
            borders = OxmlElement("w:tcBorders")
            for edge in ("top", "left", "bottom", "right"):
                el = OxmlElement("w:" + edge)
                for k, val in {"val": "single", "sz": "4", "color": "D9D9D9"}.items():
                    el.set(qn("w:" + k), val)
                borders.append(el)
            pr.append(borders)
            margins = OxmlElement("w:tcMar")
            for edge in ("top", "left", "bottom", "right"):
                el = OxmlElement("w:" + edge)
                el.set(qn("w:w"), "90")
                el.set(qn("w:type"), "dxa")
                margins.append(el)
            pr.append(margins)
            if index == 0:
                shade = OxmlElement("w:shd")
                shade.set(qn("w:fill"), "E9EEEE")
                pr.append(shade)
            for p in cell.paragraphs:
                p.paragraph_format.space_after = Pt(3)
                for run in p.runs:
                    run.font.size = Pt(9)
                    run.bold = index == 0
    d.add_paragraph("Итого к оплате: {{ gross }} ₽", "Heading 1")
    d.add_paragraph("В том числе НДС: {{ vat }} ₽. Стоимость без НДС: {{ net }} ₽.")
    d.add_paragraph("Условия поставки и оплаты", "Heading 1")
    d.add_paragraph(
        "Оплата: 100% предоплата.\nПоставка: {{ delivery_terms }}\n"
        "Получение: {{ collection }}\nПредложение действительно до {{ valid_until }} включительно."
    )
    d.add_paragraph("{{ fx_note }}")
    d.add_paragraph("Для подготовки договора свяжитесь с менеджером и направьте реквизиты вашей организации.")
    d.save(target)


def generate(letterhead, view, soffice="soffice"):
    if view["status"] != "finished":
        raise BusinessError("Генерация доступна для завершённой версии.")
    p = view["payload"]
    with tempfile.TemporaryDirectory(prefix="bp_doc_") as temp:
        root = Path(temp)
        template = root / "template.docx"
        build_template(letterhead, template)
        doc = DocxTemplate(template)
        items = [
            dict(i, unit_display=rub(i["unit_price"]), total_display=rub(i["line_total"])) for i in p["items"]
        ]
        fx = [
            f"{i['sku']}: {i['currency']}, курс {i['rate']} ₽ за 1 ед. на {i['rate_date']}."
            for i in p["items"]
            if i["currency"] != "RUB"
        ]
        context = dict(
            p,
            items=items,
            number=f"КП-{view['id']:05d}",
            version=view["version"],
            issued=date.fromisoformat(view["created_at"][:10]).strftime("%d.%m.%Y"),
            gross=rub(p["totals"]["gross"]),
            vat=rub(p["totals"]["vat"]),
            net=rub(p["totals"]["net"]),
            fx_note="\n".join(fx),
        )
        context["valid_until"] = date.fromisoformat(p["valid_until"]).strftime("%d.%m.%Y")
        doc.render(context, jinja_env=SandboxedEnvironment(undefined=StrictUndefined), autoescape=True)
        output = root / "proposal.docx"
        doc.save(output)
        profile = (root / "lo_profile").as_uri()
        subprocess.run(
            [
                soffice,
                f"-env:UserInstallation={profile}",
                "--headless",
                "--norestore",
                "--convert-to",
                "pdf",
                "--outdir",
                str(root),
                str(output),
            ],
            check=True,
            capture_output=True,
            timeout=90,
        )
        pdf = root / "proposal.pdf"
        if not pdf.exists() or not pdf.read_bytes().startswith(b"%PDF"):
            raise BusinessError("Не удалось сформировать PDF.")
        return output.read_bytes(), pdf.read_bytes()
